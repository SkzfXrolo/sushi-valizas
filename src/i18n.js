const LANG_KEY = 'sushi-valizas-lang'
const SUPPORTED = ['es', 'en', 'pt']

export function getLang() {
  const saved = localStorage.getItem(LANG_KEY)
  if (SUPPORTED.includes(saved)) return saved
  return 'es'
}

export function setLang(lang) {
  if (!SUPPORTED.includes(lang)) return
  localStorage.setItem(LANG_KEY, lang)
  document.documentElement.lang = lang
  applyI18n()
  window.dispatchEvent(new CustomEvent('sushi:lang', { detail: { lang } }))
}

export function t(key, vars = {}) {
  const lang = getLang()
  let out = dict[lang]?.[key] ?? dict.es[key] ?? key
  for (const [k, v] of Object.entries(vars)) {
    out = out.replaceAll(`{${k}}`, String(v))
  }
  return out
}

export function applyI18n() {
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n')
    if (!key) return
    el.textContent = t(key)
  })
  const title = t('meta.title')
  if (title && document.body.dataset.page === 'home') document.title = title
  const desc = document.querySelector('meta[name="description"]')
  if (desc && document.body.dataset.page === 'home') desc.setAttribute('content', t('meta.desc'))
  document.querySelectorAll('[data-lang]').forEach((btn) => {
    btn.setAttribute('aria-pressed', String(btn.getAttribute('data-lang') === getLang()))
  })
}
